import {
  corridor,
  polygon,
  rectangle,
  type Polygon,
  type WalkRegion,
} from "./navigation";
import type { Point, Rect } from "./types";

export const LAYOUT_REVISION = 12;
export interface Obstacle {
  name: string;
  polygon: Polygon;
}
export interface WorldMechanism {
  id: string;
  kind: "tool" | "breakable" | "lever" | "gate" | "cache";
  name: string;
  position: Point;
  approach: Point;
  width: number;
  height: number;
  requires?: string[];
  controlledBy?: string;
  hint: string;
  complete: string;
  reward?: string;
}
export interface BuiltSurface {
  name: string;
  path: number[][];
  width: number;
  material: "stone" | "wood";
  requires?: string;
}
export interface WorldDesign {
  regions: WalkRegion[];
  obstacles: Obstacle[];
  blockers: Polygon[];
  positions: Record<string, Point>;
  approaches: Record<string, Point>;
  baked: Record<string, Polygon>;
  solidProps: Record<string, Rect>;
  spawn: Point;
  exit: Point;
  mechanisms: WorldMechanism[];
  surfaces: BuiltSurface[];
  occluders: { polygon: Polygon; depth: number }[];
  puzzleAccess: Record<string, string[]>;
}
const area = (
  name: string,
  coords: number[][],
  requires?: string,
): WalkRegion => ({ name, polygon: polygon(coords), requires });
const path = (
  name: string,
  coords: number[][],
  width: number,
  requires?: string,
) => corridor(name, coords, width).map((r) => ({ ...r, requires }));
const obstacle = (name: string, coords: number[][]): Obstacle => ({
  name,
  polygon: polygon(coords),
});
const box = (
  name: string,
  x: number,
  y: number,
  w: number,
  h: number,
): Obstacle => ({ name, polygon: rectangle(x, y, w, h) });
type Input = Partial<WorldDesign> & {
  spawn: Point;
  regions: WalkRegion[];
  anchors: Record<string, [number, number, number, number]>;
};
function world(input: Input): WorldDesign {
  const positions: Record<string, Point> = {},
    approaches: Record<string, Point> = {};
  for (const [id, [x, y, sx, sy]] of Object.entries(input.anchors)) {
    positions[id] = { x, y };
    approaches[id] = { x: sx, y: sy };
  }
  return {
    regions: input.regions,
    obstacles: input.obstacles ?? [],
    blockers: (input.obstacles ?? []).map((o) => o.polygon),
    positions,
    approaches,
    baked: input.baked ?? {},
    solidProps: input.solidProps ?? {},
    spawn: input.spawn,
    exit: positions.exit,
    mechanisms: input.mechanisms ?? [],
    surfaces: input.surfaces ?? [],
    occluders: input.occluders ?? [],
    puzzleAccess: input.puzzleAccess ?? {},
  };
}
